#!/usr/bin/env node
// ============================================================================
// scripts/generate-font-manifest.mjs
//
// Run this any time you add or remove files in /fonts (e.g. after pushing
// new .woff2 files to GitHub):
//
//     node scripts/generate-font-manifest.mjs
//
// It scans fonts/*.woff2, and regenerates:
//   - fonts/manifest.json     (read by the admin panel to build the font
//                               picker — this is the ONLY thing that decides
//                               which fonts show up as choices)
//   - css/fonts-generated.css (the actual @font-face rules, loaded on every
//                               page so the chosen font renders)
//
// FILE NAMING CONVENTION your .woff2 files need to follow:
//   FamilyName-Weight.woff2          e.g. Lora-Bold.woff2
//   FamilyName-WeightItalic.woff2    e.g. Lora-BoldItalic.woff2
// Recognized weight words: Thin, ExtraLight, Light, Regular, Medium,
// SemiBold, Bold, ExtraBold, Black (case-insensitive). Anything else
// defaults to Regular/400 — the font will still work, just check the
// generated manifest.json to confirm it landed on the weight you meant.
// ============================================================================

import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const FONTS_DIR = path.join(ROOT, "fonts");

const WEIGHT_MAP = {
  thin: 100,
  extralight: 200,
  light: 300,
  regular: 400,
  medium: 500,
  semibold: 600,
  bold: 700,
  extrabold: 800,
  black: 900,
};

function parseFilename(filename) {
  const stem = filename.replace(/\.woff2$/i, "");
  const dashIndex = stem.indexOf("-");
  const family = dashIndex === -1 ? stem : stem.slice(0, dashIndex);
  const rest = dashIndex === -1 ? "" : stem.slice(dashIndex + 1);
  const isItalic = /italic$/i.test(rest);
  const weightWord = rest.replace(/italic$/i, "") || "Regular";
  const weight = WEIGHT_MAP[weightWord.toLowerCase()] ?? 400;
  return { family, weight, style: isItalic ? "italic" : "normal" };
}

function main() {
  let files;
  try {
    files = readdirSync(FONTS_DIR).filter((f) => f.toLowerCase().endsWith(".woff2"));
  } catch (err) {
    console.error(`Could not read ${FONTS_DIR} — does the fonts/ folder exist?`);
    process.exit(1);
  }

  if (!files.length) {
    console.warn("No .woff2 files found in fonts/ — manifest will be empty.");
  }

  const families = new Map();
  for (const file of files.sort()) {
    const { family, weight, style } = parseFilename(file);
    if (!families.has(family)) families.set(family, []);
    families.get(family).push({ weight, style, file });
  }

  const manifest = {
    fonts: [...families.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([family, fontFiles]) => ({
        family,
        files: fontFiles.sort((a, b) => a.weight - b.weight || a.style.localeCompare(b.style)),
      })),
  };

  writeFileSync(path.join(FONTS_DIR, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  const cssBlocks = manifest.fonts.flatMap((f) =>
    f.files.map(
      (ff) => `@font-face {
  font-family: "${f.family}";
  src: url("../fonts/${ff.file}") format("woff2");
  font-weight: ${ff.weight};
  font-style: ${ff.style};
  font-display: swap;
}`
    )
  );

  const cssHeader = `/* AUTO-GENERATED by scripts/generate-font-manifest.mjs — do not hand-edit.
   Regenerate with: node scripts/generate-font-manifest.mjs */\n\n`;
  writeFileSync(path.join(ROOT, "css", "fonts-generated.css"), cssHeader + cssBlocks.join("\n\n") + "\n");

  console.log(`Found ${manifest.fonts.length} font famil${manifest.fonts.length === 1 ? "y" : "ies"}:`);
  for (const f of manifest.fonts) console.log(`  - ${f.family} (${f.files.length} files)`);
  console.log("\nWrote fonts/manifest.json and css/fonts-generated.css");
}

main();
